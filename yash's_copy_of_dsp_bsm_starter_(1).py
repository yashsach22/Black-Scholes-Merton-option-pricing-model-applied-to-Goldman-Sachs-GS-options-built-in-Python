"""### Historical volatility
Write `historical_vol(prices)`:
1. Compute daily **log returns**: ln(P_today / P_yesterday)
2. Take their standard deviation
3. Annualize: multiply by √252 (trading days in a year)
"""

def historical_vol(prices):
    """prices: a pandas Series of daily closing prices. Returns annualized volatility."""
    log_returns = np.log(prices / prices.shift(1)).dropna()
    return log_returns.std() * np.sqrt(252)
