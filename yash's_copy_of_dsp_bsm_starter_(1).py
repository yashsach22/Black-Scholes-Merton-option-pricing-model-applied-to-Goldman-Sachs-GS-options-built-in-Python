"""## Part 2: The BSM Pricer

$$C = S e^{-qT} N(d_1) - K e^{-rT} N(d_2)$$

$$d_1 = \frac{\ln(S/K) + (r - q + \tfrac{1}{2}\sigma^2)T}{\sigma\sqrt{T}}, \qquad d_2 = d_1 - \sigma\sqrt{T}$$

`N()` is the standard normal CDF: use `norm.cdf()`.
"""

def d1_d2(S, K, T, r, q, sigma):
    """Computes d1 and d2 (already done for you)."""
    d1 = (np.log(S / K) + (r - q + 0.5 * sigma**2) * T) / (sigma * np.sqrt(T))
    d2 = d1 - sigma * np.sqrt(T)
    return d1, d2


def bsm_call_price(S, K, T, r, q, sigma):
    """Black-Scholes-Merton price of a European call with dividend yield q."""
    d1, d2 = d1_d2(S, K, T, r, q, sigma)
    return S * np.exp(-q*T) * norm.cdf(d1) - K * np.exp(-r*T) * norm.cdf(d2)
    raise NotImplementedError("Fill this in!")


