"""## Part 3: The Greeks

| Greek | Formula | Meaning |
|---|---|---|
| Delta | $e^{-qT} N(d_1)$ | $ change in option per $1 move in the stock |
| Gamma | $\frac{e^{-qT} N'(d_1)}{S \sigma \sqrt{T}}$ | how fast delta changes |
| Vega | $S e^{-qT} N'(d_1)\sqrt{T} \;/\; 100$ | $ change per 1 percentage-point rise in volatility |
| Theta | $\Big[-\frac{S e^{-qT} N'(d_1)\sigma}{2\sqrt{T}} - rKe^{-rT}N(d_2) + qSe^{-qT}N(d_1)\Big] / 365$ | $ lost per day from time passing |

$N'(x)$ is the standard normal PDF: use `norm.pdf()`.
"""

def greeks(S, K, T, r, q, sigma):
    """Returns a dict with delta, gamma, vega (per 1 vol point), theta (per day)."""
    d1, d2 = d1_d2(S, K, T, r, q, sigma)
    delta = np.exp(-q * T) * norm.cdf(d1)
    gamma = np.exp(-q * T) * norm.pdf(d1) / (S * sigma * np.sqrt(T))
    vega = S * np.exp(-q * T) * norm.pdf(d1) * np.sqrt(T) / 100
    theta = (-(S * np.exp(-q * T) * norm.pdf(d1) * sigma / (2 * np.sqrt(T))) - (r * K * np.exp(-r * T) * norm.cdf(d2)) + (q * S * np.exp(-q * T) * norm.cdf(d1))) / 365
    # TODO: compute delta, gamma, vega, theta using the table above
